public class CollectionComparison {
    public static void main(String[] args) {
        System.out.println("ArrayList:");
        System.out.println("- Ordered");
        System.out.println("- Allows duplicates");
        System.out.println("- Good for storing lists");

        System.out.println("\nHashSet:");
        System.out.println("- Unique elements only");
        System.out.println("- No duplicates");
        System.out.println("- Good for skills, tags, and unique items");

        System.out.println("\nHashMap:");
        System.out.println("- Stores key-value pairs");
        System.out.println("- Keys are unique");
        System.out.println("- Good for student records, phone books, and marks");
    }
}